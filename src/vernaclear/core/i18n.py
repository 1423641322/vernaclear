def normalize_ui_language(language: str) -> str:
    return "en" if str(language).lower().startswith("en") else "zh"


def tr(language: str, key: str, **values: Any) -> str:
    locale = normalize_ui_language(language)
    template = TEXT.get(locale, TEXT["zh"]).get(key, TEXT["zh"].get(key, key))
    return template.format(**values) if values else template
